"""Image discovery, EXIF-aware loading, and padded region cropping for PersonSort."""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path, PurePosixPath
from typing import Iterable, Optional

try:
    import numpy as np
except ImportError:
    np = None  # type: ignore

try:
    from PIL import Image, ImageOps
except ImportError:
    Image = None  # type: ignore
    ImageOps = None  # type: ignore

try:
    import cv2
except ImportError:
    cv2 = None  # type: ignore

from models import BoundingBox

logger = logging.getLogger(__name__)

# Supported photo file extensions (lowercase)
SUPPORTED_EXTENSIONS: frozenset[str] = frozenset(
    {".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tif", ".tiff"}
)

# Reserved filenames generated by PersonSort that should be skipped when scanning folders
IGNORED_FILENAMES: frozenset[str] = frozenset(
    {"_reference_crop.jpg", "_reference_crop.png"}
)


def is_supported_image_name(filename: str) -> bool:
    """Return True if a filename (local or remote) has a supported image extension."""
    if not filename:
        return False
    p = PurePosixPath(filename.replace("\\", "/"))
    name = p.name
    if not name or name.startswith("."):
        return False
    return (
        p.suffix.lower() in SUPPORTED_EXTENSIONS
        and name.lower() not in IGNORED_FILENAMES
    )


def is_supported_image(path: Path) -> bool:
    """Return True if `path` is a regular file with a supported image extension."""
    return path.is_file() and is_supported_image_name(path.name)


def detect_local_dropbox_root() -> Optional[Path]:
    """
    Detect the locally synced Dropbox desktop folder if installed on this machine.
    Checks standard Dropbox Desktop `info.json` locations and `~/Dropbox`.
    """
    candidates: list[Path] = []
    for env_var in ("LOCALAPPDATA", "APPDATA"):
        val = os.environ.get(env_var, "").strip()
        if val:
            candidates.append(Path(val) / "Dropbox" / "info.json")
    candidates.append(Path.home() / ".dropbox" / "info.json")

    for info_path in candidates:
        if not info_path.is_file():
            continue
        try:
            data = json.loads(info_path.read_text(encoding="utf-8"))
        except Exception:
            continue
        for account_key in ("personal", "business"):
            section = data.get(account_key)
            if isinstance(section, dict):
                raw_path = section.get("path")
                if isinstance(raw_path, str) and raw_path.strip():
                    p = Path(raw_path.strip())
                    if p.is_dir():
                        return p

    default_dir = Path.home() / "Dropbox"
    if default_dir.is_dir():
        return default_dir
    return None


def resolve_local_dropbox_file(
    dropbox_path_display: str,
    expected_size: Optional[int] = None,
    local_root: Optional[Path] = None,
) -> Optional[Path]:
    """
    Given a Dropbox path (e.g. '/Events/Game1/IMG_001.jpg'), resolve the matching
    local synced file if it exists on disk and matches `expected_size`.
    """
    root = local_root if local_root is not None else detect_local_dropbox_root()
    if root is None or not root.is_dir():
        return None

    rel = (dropbox_path_display or "").strip().replace("\\", "/").lstrip("/")
    if not rel:
        return None

    candidate = root / Path(rel)
    if not candidate.is_file():
        return None

    if expected_size is not None and expected_size > 0:
        try:
            if candidate.stat().st_size != expected_size:
                return None
        except OSError:
            return None

    return candidate


def scan_images(root_dir: Path, recursive: bool = True) -> list[Path]:
    """
    Find all supported image files inside `root_dir` in deterministic sorted order.
    Automatically skips hidden files and generated `_reference_crop` thumbnails.
    """
    if not root_dir.exists():
        raise FileNotFoundError(f"Image directory does not exist: {root_dir}")
    if not root_dir.is_dir():
        raise NotADirectoryError(f"Path is not a directory: {root_dir}")

    iterator: Iterable[Path] = root_dir.rglob("*") if recursive else root_dir.iterdir()
    images = [p.resolve() for p in iterator if is_supported_image(p)]
    images.sort(key=lambda p: str(p).lower())
    return images


def load_image_bgr(image_path: Path) -> np.ndarray | None:
    """
    Load an image from disk as a 3-channel BGR numpy array (uint8), normalizing
    any EXIF orientation tags so rotated portrait sports photos are upright.

    Returns None if the file is unreadable or corrupted.
    """
    if not image_path.exists():
        logger.warning("Image file does not exist: %s", image_path)
        return None

    # Preferred path: Pillow handles Unicode paths on Windows and EXIF orientation cleanly
    if Image is not None and ImageOps is not None:
        try:
            with Image.open(image_path) as pil_img:
                pil_img = ImageOps.exif_transpose(pil_img)
                rgb_img = pil_img.convert("RGB")
                rgb_array = np.asarray(rgb_img, dtype=np.uint8)
                # Convert RGB -> BGR for OpenCV / InsightFace compatibility
                bgr_array = np.ascontiguousarray(rgb_array[:, :, ::-1])
                return bgr_array
        except Exception as exc:
            logger.warning("Failed to load image with Pillow (%s): %s", image_path, exc)

    # Fallback path: OpenCV with numpy.fromfile (supports Windows Unicode paths)
    if cv2 is not None:
        try:
            raw_bytes = np.fromfile(str(image_path), dtype=np.uint8)
            bgr_array = cv2.imdecode(raw_bytes, cv2.IMREAD_COLOR)
            if bgr_array is not None:
                return bgr_array
        except Exception as exc:
            logger.warning("Failed to load image with OpenCV (%s): %s", image_path, exc)

    return None


def crop_region(
    image_bgr: np.ndarray,
    bbox: BoundingBox,
    padding_ratio: float = 0.0,
) -> np.ndarray | None:
    """
    Crop `bbox` from `image_bgr` with an optional proportional margin (`padding_ratio`).

    For example, `padding_ratio=0.25` expands the crop by 25% of the box's width/height
    on each side (clamped to the image boundaries), which is useful for face thumbnails
    and torso jersey crops.
    """
    if image_bgr is None or image_bgr.size == 0:
        return None

    img_h, img_w = image_bgr.shape[:2]
    if bbox.width <= 0 or bbox.height <= 0:
        return None

    pad_x = int(round(bbox.width * max(0.0, padding_ratio)))
    pad_y = int(round(bbox.height * max(0.0, padding_ratio)))

    x1 = max(0, bbox.x1 - pad_x)
    y1 = max(0, bbox.y1 - pad_y)
    x2 = min(img_w, bbox.x2 + pad_x)
    y2 = min(img_h, bbox.y2 + pad_y)

    if x2 <= x1 or y2 <= y1:
        return None

    return image_bgr[y1:y2, x1:x2].copy()


def save_image_bgr(image_bgr: np.ndarray, output_path: Path, jpeg_quality: int = 92) -> bool:
    """
    Save a BGR numpy array to `output_path`, creating parent directories if needed.
    Supports Unicode file paths on Windows.
    """
    if image_bgr is None or image_bgr.size == 0:
        return False

    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Preferred path: Pillow
    if Image is not None:
        try:
            rgb_array = image_bgr[:, :, ::-1]
            pil_img = Image.fromarray(rgb_array)
            save_kwargs = {}
            if output_path.suffix.lower() in {".jpg", ".jpeg"}:
                save_kwargs["quality"] = jpeg_quality
                save_kwargs["subsampling"] = 0
            pil_img.save(output_path, **save_kwargs)
            return True
        except Exception as exc:
            logger.warning("Pillow failed to save %s: %s", output_path, exc)

    # Fallback path: OpenCV imencode + tofile
    if cv2 is not None:
        try:
            ext = output_path.suffix.lower() or ".jpg"
            params = (
                [int(cv2.IMWRITE_JPEG_QUALITY), jpeg_quality]
                if ext in {".jpg", ".jpeg"}
                else []
            )
            success, encoded = cv2.imencode(ext, image_bgr, params)
            if success:
                encoded.tofile(str(output_path))
                return True
        except Exception as exc:
            logger.warning("OpenCV failed to save %s: %s", output_path, exc)

    return False
